#!/usr/bin/env python3
"""Write nv2a-key-schema.h: a hash of the headers that define the Vulkan
renderer's pipeline and shader-module keys (vk/keys.h, the GLSL state
headers and the register enums they hold), as NV2A_KEY_SCHEMA.

The pipeline prewarm (hw/xbox/nv2a/pgraph/vk/prewarm.c) records keys in a
manifest and replays them at the next launch: a build whose key headers
differ starts a new manifest, so it never replays bytes whose meaning
changed. Edits elsewhere (renderer state, generators) keep the manifest.

usage: nv2a-key-schema.py OUTPUT INPUT...
"""
import hashlib
import sys

out, inputs = sys.argv[1], sys.argv[2:]
h = hashlib.sha256()
for path in sorted(inputs, key=lambda p: p.replace('\\', '/').rsplit('/', 3)[-3:]):
    with open(path, 'rb') as f:
        # Line endings don't change a schema (Windows checkouts)
        h.update(f.read().replace(b'\r\n', b'\n'))
text = ('/* Generated by scripts/nv2a-key-schema.py: do not edit */\n'
        '#define NV2A_KEY_SCHEMA 0x%sULL\n' % h.hexdigest()[:16])
try:
    with open(out) as f:
        if f.read() == text:
            sys.exit(0)
except OSError:
    pass
with open(out, 'w') as f:
    f.write(text)
